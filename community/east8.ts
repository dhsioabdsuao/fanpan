// 东八区日期工具(纯函数,时间由调用方注入便于测试)
// ─────────────────────────────────────────────────────────────

/** 当前(或指定)时刻的东八区日期键 'YYYY-MM-DD'(日限重置键) */
export function todayEast8(now: number = Date.now()): string {
  return new Date(now + 8 * 3600_000).toISOString().slice(0, 10)
}
