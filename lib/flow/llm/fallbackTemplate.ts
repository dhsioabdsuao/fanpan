const TEMPLATE_1A = `你的命局五行齐全,各自的力量比较均衡,从金到水、水到木、木到火、火到土、土到金的相生链路都能接续——没有某一种力量特别盛,也没有某一种力量明显薄。这种命局结构,传统命书称作"周流不滞",指五行的气循环流转,没有大的堵点。

需要说明的是,"流通"描述的是命局内部的结构,不直接等同于人生的顺与不顺。它意味着你的命局本身没有显著的偏向——力量分布平稳,没有特别突出的优势,也没有特别突出的短板。这种结构对外部变化的承接力相对均衡,各方面的能量都能正常调度起来。`

function buildTemplate1B(factPack: FlowFactPack): string {
  const allElements: ElementType[] = ['金', '木', '水', '火', '土']
  const sorted = [...allElements].sort(
    (a, b) => factPack.elementForce.forces[b].force - factPack.elementForce.forces[a].force
  )
  const strongestA = sorted[0]
  const strongestB = sorted[1] ?? sorted[0]
  const weakest = sorted[4]

  return `你的命局五行齐全,但力量不是均匀分布的——${strongestA} 与 ${strongestB} 比较旺,${weakest} 相对薄一些。即便如此,五个相生链路都能接续,从金到水、水到木一路转下去,没有明显的断点。

这种结构,传统命书会归在"流通"一类,但跟"周流不滞"略有不同:命局里有自己的主轴,有强有弱,带着一种节奏感。它意味着你的命局有清晰的力量偏向——以 ${strongestA} 与 ${strongestB} 为主轴展开,但整体仍然能循环起来,不会卡死。`
}

