export function generateFallbackFromTemplate(factPack: FlowFactPack): string {
  const primaryType = factPack.structureSummary.primaryTypes[0]?.type
  if (!primaryType) {
    return TEMPLATE_5A
  }

  const template = FALLBACK_MAP[primaryType]
  if (!template) {
    return TEMPLATE_5A
  }

  if (typeof template === 'function') {
    return template(factPack)
  }

  return template
}
