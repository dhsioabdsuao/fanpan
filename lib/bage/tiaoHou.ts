/**
 * 根据日主和月令查《穷通宝鉴》调候用神。
 * @returns 调候天干列表（可能为空），按原文顺序排列
 */
export function getTiaoHouYongShen(dayMaster: string, monthBranch: string): string[] {
  const inner = TIAO_HOU_TABLE.get(dayMaster)
  if (!inner) return []
  return inner.get(monthBranch) ?? []
}
