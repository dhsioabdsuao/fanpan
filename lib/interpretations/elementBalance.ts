export function analyzeElements(
  elementCount: Record<ElementType, number>,
): ElementBalanceItem[] {
  const elements: ElementType[] = ['金', '木', '水', '火', '土']
  return elements.map((el) => {
    const count = elementCount[el]
    const state = determineState(count)
    const item: ElementBalanceItem = {
      element: el,
      state,
      description: DESCRIPTIONS[el][state],
    }
    if (state === '缺失' || state === '过旺') {
      item.suggestion = SUGGESTIONS[el][state]
    }
    return item
  })
}
