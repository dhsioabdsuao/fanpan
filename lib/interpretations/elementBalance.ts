import type { ElementType } from '@/types/bazi'

export type ElementState = '缺失' | '偏弱' | '平和' | '偏旺' | '过旺'

export type ElementBalanceItem = {
  element: ElementType
  state: ElementState
  description: string
  suggestion?: string
}

function determineState(count: number): ElementState {
  if (count === 0) return '缺失'
  if (count === 1) return '偏弱'
  if (count === 2) return '平和'
  if (count === 3) return '偏旺'
  return '过旺'
}

